import type { CriterionDef, PillarDef } from '../framework';

/**
 * The criteria library.
 *
 * Each criterion is a statement that can be argued from: it carries the standard
 * it comes from, the platforms it applies to, whether it can be measured, and
 * the measurements that decide it. `checks` are the engine's own measurement
 * ids (`ACC-001`, `UX-014`, `PERF-003`); they stay out of the report, which
 * quotes the criterion and the standard instead.
 *
 * Criteria with no checks are not gaps in the engine — they are the parts of an
 * audit that need someone to work the product. They are listed in the report as
 * reviewer tasks rather than being quietly dropped.
 */

